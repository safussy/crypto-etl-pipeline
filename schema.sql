--  Crypto ETL Relational Database Schema 
DROP TABLE IF EXISTS fct_crypto_price;
DROP TABLE IF EXISTS dim_crypto_asset;

-- Dim table: static metadata for each cryptocurrency asset 
CREATE TABLE dim_crypto_asset (
    coin_id TEXT PRIMARY KEY NOT NULL,
    symbol TEXT NOT NULL,
    name TEXT NOT NULL
);

-- Fact table: time series operational snapshots and price metrics
-- Fact table with composite unique constraint for upserts
CREATE TABLE fct_crypto_price (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coin_id TEXT NOT NULL,
    current_price_usd REAL,
    market_cap REAL,
    market_cap_rank INTEGER,
    total_volume_usd REAL,
    price_change_24h_pct REAL,
    snapshot_timestamp TEXT NOT NULL,
    UNIQUE(coin_id, snapshot_timestamp),
    FOREIGN KEY (coin_id) REFERENCES dim_crypto_asset(coin_id) ON DELETE CASCADE
);

-- Index frequently queried foreign key columns for fast analytical lookups 
CREATE INDEX IF NOT EXISTS idx_fct_coin_time ON fct_crypto_price(coin_id, snapshot_timestamp);